def vector_db_selection_guide():
    """向量数据库选型指南"""
    
    guide = """
    ==================== 向量数据库选型指南 ====================
    
    【场景1：原型开发 / 个人项目】
    推荐：Chroma / FAISS
    理由：
    - 零配置，pip安装即用
    - 无需部署服务器
    - API简单易用
    - 适合数据量 < 10万
    
    【场景2：中小规模生产环境】
    推荐：Qdrant / Milvus Standalone
    理由：
    - 高性能，支持百万级向量
    - 持久化存储
    - 支持多种索引算法
    - 有REST/gRPC API
    - 适合数据量 10万-1000万
    
    【场景3：大规模企业应用】
    推荐：Milvus Cluster / Pinecone
    理由：
    - 分布式架构，支持十亿级向量
    - 高可用、多副本
    - 自动扩缩容
    - 企业级支持
    - 适合数据量 > 1000万
    
    【场景4：无运维团队 / 快速上线】
    推荐：Pinecone / Zilliz Cloud
    理由：
    - 全托管服务
    - 零运维
    - 按使用量付费
    - 全球多区域部署
    
    【场景5：边缘设备 / 嵌入式应用】
    推荐：FAISS / SQLite-VSS
    理由：
    - 纯C++实现，性能高
    - 资源占用小
    - 可嵌入应用
    - 无外部依赖
    
    ==================== 性能对比 ====================
    
    数据库        延迟(1M向量)    吞吐量    扩展性    易用性
    ---------------------------------------------------
    FAISS         <1ms           高        低        中
    Chroma        5-10ms         中        低        高
    Qdrant        5-15ms         高        中        高
    Milvus        10-20ms        高        极高      中
    Pinecone      20-50ms        中        极高      高
    
    ==================== 决策树 ====================
    
    是否需要分布式？
    ├─ 是 → 选择 Milvus / Pinecone
    └─ 否 → 数据量如何？
        ├─ <10万 → Chroma / FAISS
        ├─ 10万-1000万 → Qdrant / Milvus单机
        └─ >1000万 → Milvus集群
    
    是否有运维团队？
    ├─ 否 → 选择 SaaS (Pinecone / Zilliz)
    └─ 是 → 选择自托管
    
    ==================================================
    """
    
    print(guide)

if __name__ == "__main__":
    vector_db_selection_guide()

# 01_个人名片.py —— 用变量存信息，打印一张整齐的名片
# 参考答案：先自己写，卡住了再看这里

name = "林小雨"      # 文字要加引号
city = "杭州"
age = 18            # 年龄是数字，不加引号——练习的重点就在这

# age 是数字，拼进文字前必须用 str() 变身，
# 否则就是"数字 + 文字"的老坑，TypeError 直接报错
print("==========")
print("姓名：" + name)
print("城市：" + city)
print("年龄：" + str(age))
print("==========")

# 02_找零计算器.py —— 问付款金额和价格，算出找零
# 参考答案：先自己写，卡住了再看这里

# 钱可能带小数（比如 37.5 元），所以用 float 转换
paid = float(input("顾客付了多少钱？"))
price = float(input("商品一共多少钱？"))

change = paid - price

# change 是小数，拼进文字前先 str() 变身。
# 金额带小数时结果可能拖一条小尾巴（如 63.00000000000001），
# 这是计算机存小数的近似造成的，不是你写错了，第 3 课教你打印得体面
print("找零：" + str(change) + " 元")

# 练习 1：闰年判断（必做）
# 规则：能被 4 整除且不能被 100 整除，或者能被 400 整除，就是闰年。
# 易错点：判断整除用 % 求余数，不是用除号 /。

year = int(input("输入一个年份："))

if (year % 4 == 0 and year % 100 != 0) or (year % 400 == 0):
    print(f"{year} 年是闰年，2 月有 29 天。")
else:
    print(f"{year} 年不是闰年，2 月只有 28 天。")

# 自查：2024 是闰年，1900 不是（被 100 整除但不被 400 整除），2000 是闰年。

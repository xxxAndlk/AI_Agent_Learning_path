# ============ Lambda的限制 ============

# 1. 只能包含表达式，不能包含语句
# 正确：使用三元表达式
abs_val = lambda x: x if x >= 0 else -x

# 2. 不能定义默认参数以外的参数
power = lambda x, n=2: x ** n
print(power(3))    # 9 (n=2)
print(power(3, 3)) # 27 (n=3)

# Lambda的限制导致的使用场景选择
# 适合用Lambda的场景：
# - 简单的数据转换
# - 排序/过滤的key函数
# - 回调函数
# - 一次性使用的函数

# 不适合用Lambda的场景：
# - 复杂逻辑（超过几行）
# - 需要多次复用的函数
# - 需要文档字符串的函数
# - 需要类型提示的函数

# 递归分块器是LangChain中最强大和常用的分块工具
# 它按照分隔符优先级层层递进，直到满足大小要求

from langchain_text_splitters import RecursiveCharacterTextSplitter

# 创建一个较长的示例文档，包含多个段落
long_document = """
第一章 机器学习概述

机器学习是一门多领域交叉学科，涉及概率论、统计学、逼近论、凸分析、
算法复杂度理论等多门学科。专门研究计算机怎样模拟或实现人类的学习行为，
以获取新的知识或技能，重新组织已有的知识结构使之不断改善自身的性能。

机器学习算法可以分为以下几类：

1. 监督学习
监督学习是从标记的训练数据中学习预测模型的机器学习问题。
训练数据由一组训练实例组成，每个实例由输入向量和对应的期望输出组成。
常见的监督学习算法包括线性回归、逻辑回归、决策树、支持向量机等。

2. 无监督学习
无监督学习是从未标记的数据中学习隐藏模式的机器学习问题。
与监督学习不同，无监督学习不需要预先标记的训练数据。
常见的无监督学习算法包括聚类、降维、异常检测等。

3. 强化学习
强化学习是智能体通过与环境交互来学习最优策略的机器学习范式。
智能体根据当前状态采取行动，环境返回奖励，智能体根据奖励调整策略。
常见的强化学习算法包括Q学习、深度Q网络、策略梯度等。

第二章 深度学习基础

深度学习是机器学习的一个分支，它是一种以人工神经网络为架构，
对数据进行表征学习的算法。深度学习通过构建多层神经网络，
自动学习数据的层次化表征。

神经网络的基本单元是神经元，也称为节点。每个神经元接收多个输入，
对它们进行加权求和，然后通过激活函数产生输出。多个神经元组成一层，
多层神经元组成神经网络。

常见的激活函数包括：
- ReLU函数：f(x) = max(0, x)，计算简单，是目前最常用的激活函数
- Sigmoid函数：f(x) = 1 / (1 + e^(-x))，输出范围在(0, 1)之间
- Tanh函数：f(x) = (e^x - e^(-x)) / (e^x + e^(-x))，输出范围在(-1, 1)之间
"""

# 创建递归分块器
# 递归分块器的工作流程：
# 1. 首先尝试用第一个分隔符（\n\n）分割文本
# 2. 如果分割后的块大于chunk_size，继续用下一个分隔符（\n）分割
# 3. 重复这个过程，直到所有块都满足大小要求
recursive_splitter = RecursiveCharacterTextSplitter(
    chunk_size=300,           # 每个块最大300字符
    chunk_overlap=30,         # 重叠30字符
    # 按优先级排列的分隔符列表
    # 越靠前的分隔符越优先使用，表示更大的语义单元边界
    separators=[
        "\n\n",              # 段落分隔符，最优先
        "\n",                # 换行符
        "。", "！", "？",    # 句号、感叹号、问号
        "；", "，",          # 分号、逗号
        " " ,                # 空格
        ""                   # 字符级分割，作为最后手段
    ],
    length_function=len,
    # 是否保留分隔符，默认True会保留分隔符
    keep_separator=True,
)

# 执行递归分块
recursive_chunks = recursive_splitter.split_text(long_document)

print(f"递归分块结果：共 {len(recursive_chunks)} 个块\n")

for i, chunk in enumerate(recursive_chunks):
    # 每块显示前80个字符作为预览
    preview = chunk[:80].replace("\n", " ")
    print(f"[块{i+1}] {len(chunk)}字符: {preview}...")

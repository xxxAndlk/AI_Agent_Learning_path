# 导入SentenceTransformer：Sentence-BERT模型的Python封装库
# 用于将句子转换为语义向量表示
from sentence_transformers import SentenceTransformer

# 导入NumPy：Python数值计算库
# 用于高效处理多维数组（向量）和数学运算
import numpy as np

# ============================================================
# 步骤1：加载预训练Embedding模型
# ============================================================
# 'all-MiniLM-L6-v2'是轻量级预训练模型
# - all: 表示在多种数据上预训练
# - MiniLM: 模型架构（MiniLM变压器）
# - L6: 6层Transformer结构
# - v2: 版本号
# 输出维度：384维向量，适合大多数场景
model = SentenceTransformer('all-MiniLM-L6-v2')

# ============================================================
# 步骤2：准备待嵌入的句子列表
# ============================================================
# 三个测试句子：
# - 句子0和2完全相同（用于验证相同语义得到高相似度）
# - 句子1语义不同（用于验证不同语义得到低相似度）
sentences = [
    "这是一个示例句子。",       # 句子0
    "另一个不同的句子。",       # 句子1（与0语义不同）
    "这是一个示例句子。"        # 句子2（与0完全相同）
]

# ============================================================
# 步骤3：生成句子嵌入向量
# ============================================================
# model.encode()是核心方法：
# - 输入：句子列表（字符串列表）
# - 输出：numpy数组，形状为 (句子数量, 向量维度)
# - 内部流程：分词 → 编码 → 池化 → 归一化
embeddings = model.encode(sentences)

# 打印嵌入向量的形状信息
# 预期输出：(3, 384) 表示3个句子，每个句子被编码为384维向量
print("Embedding形状:", embeddings.shape)

# ============================================================
# 步骤4：计算句子间的语义相似度
# ============================================================
# 余弦相似度计算简化版：
# 模型输出的向量已经过L2归一化，因此直接使用点积即为余弦相似度
# 公式：cosine(A,B) = A·B / (||A|| × ||B||) = A·B （归一化后）

# 计算句子0和句子1的相似度
# 预期结果：较低（因为语义不同）
similarity1 = np.dot(embeddings[0], embeddings[1])

# 计算句子0和句子2的相似度
# 预期结果：接近1（因为完全相同）
similarity2 = np.dot(embeddings[0], embeddings[2])

# 输出相似度结果
print("句子0和1的相似度:", similarity1)   # 预期：较低值，语义不同
print("句子0和2的相似度:", similarity2)   # 预期：接近1.0，完全相同
